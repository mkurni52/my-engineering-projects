import os
import torch
import torch.nn as nn
import torch.nn.functional as F
import pandas as pd
import numpy as np
from pymatgen.core.structure import Structure
from torch_geometric.data import Data, Dataset
from torch_geometric.loader import DataLoader
from torch_geometric.nn import CGConv, global_mean_pool
from sklearn.metrics import mean_absolute_error, r2_score

# 1. Define the Periodic Crystal Graph Dataset (Aligned with mofdb_client columns)
class PeriodicMOFDataset(Dataset):
    def __init__(self, cif_dir, target_csv, radius_cutoff=6.0, max_neighbors=12):
        super().__init__()
        self.cif_dir = cif_dir
        self.radius_cutoff = radius_cutoff
        self.max_neighbors = max_neighbors
        self.target_df = pd.read_csv(target_csv)
        self.mof_ids = self.target_df['mof_id'].values
        # Common elements in MOFs (H to Zn) + fallback bin
        self.elements = [1, 3, 5, 6, 7, 8, 9, 12, 13, 14, 15, 16, 17, 22, 23, 24, 25, 26, 27, 28, 29, 30, 40, 48, 0]

    def len(self):
        return len(self.mof_ids)

    def _featurize_atom(self, atomic_num):
        vec = np.zeros(len(self.elements), dtype=np.float32)
        if atomic_num in self.elements:
            vec[self.elements.index(atomic_num)] = 1.0
        else:
            vec[-1] = 1.0
        return vec

    def get(self, idx):
        mof_id = self.mof_ids[idx]
        cif_path = os.path.join(self.cif_dir, f"{mof_id}.cif")
        crystal = Structure.from_file(cif_path)

        # Node features (atomic identities)
        x = torch.tensor(np.array([self._featurize_atom(site.specie.number) for site in crystal]), dtype=torch.float)

        # Periodic edges within cutoff radius
        edge_indices, edge_attrs = [], []
        all_neighbors = crystal.get_all_neighbors(r=self.radius_cutoff, include_index=True)
        for i, neighbors in enumerate(all_neighbors):
            neighbors = sorted(neighbors, key=lambda n: n[1])[:self.max_neighbors]
            for neighbor in neighbors:
                edge_indices.append([i, neighbor[2]])
                edge_attrs.append([neighbor[1]]) # Interatomic scalar distance

        edge_index = torch.tensor(edge_indices, dtype=torch.long).t().contiguous()
        edge_attr = torch.tensor(edge_attrs, dtype=torch.float)

        # Target label: low-pressure CO2 uptake
        y_val = self.target_df.iloc[idx]['co2_uptake_low_p']
        y = torch.tensor([[y_val]], dtype=torch.float)

        return Data(x=x, edge_index=edge_index, edge_attr=edge_attr, y=y)

# 2. Build Dataset and Partition (Same 80/20 split as Random Forest for fair comparison)
print("Building 3D periodic graphs from CIF files (this may take 1-2 minutes)...")
full_dataset = PeriodicMOFDataset(cif_dir='data/cifs', target_csv='data/targets.csv')
graph_list = [full_dataset.get(i) for i in range(len(full_dataset))]

split_idx = int(len(graph_list) * 0.8)
train_loader = DataLoader(graph_list[:split_idx], batch_size=32, shuffle=True)
test_loader = DataLoader(graph_list[split_idx:], batch_size=32, shuffle=False)

# 3. Define the Crystal Graph Convolutional Neural Network (CGCNN)
class MOF_CGCNN(nn.Module):
    def __init__(self, node_dim, edge_dim, hidden_dim=64):
        super().__init__()
        self.embedding = nn.Linear(node_dim, hidden_dim)
        self.conv1 = CGConv(channels=hidden_dim, dim=edge_dim, batch_norm=True)
        self.conv2 = CGConv(channels=hidden_dim, dim=edge_dim, batch_norm=True)
        self.conv3 = CGConv(channels=hidden_dim, dim=edge_dim, batch_norm=True)
        self.fc1 = nn.Linear(hidden_dim, 32)
        self.out = nn.Linear(32, 1)

    def forward(self, data):
        x, edge_index, edge_attr, batch = data.x, data.edge_index, data.edge_attr, data.batch
        x = F.softplus(self.embedding(x))
        x = self.conv1(x, edge_index, edge_attr)
        x = self.conv2(x, edge_index, edge_attr)
        x = self.conv3(x, edge_index, edge_attr)
        x = global_mean_pool(x, batch) # Aggregate atomic states into whole-crystal representation
        x = F.softplus(self.fc1(x))
        return self.out(x)

# 4. Initialize Model, Optimizer, and GPU Device
device = torch.device('cuda' if torch.cuda.is_available() else 'cpu')
model = MOF_CGCNN(node_dim=25, edge_dim=1, hidden_dim=64).to(device)
optimizer = torch.optim.Adam(model.parameters(), lr=0.001, weight_decay=1e-5)
criterion = nn.MSELoss()

# 5. Execute Training Loop
print(f"Training CGCNN on {device}...")
for epoch in range(1, 51):
    model.train()
    total_loss = 0
    for batch in train_loader:
        batch = batch.to(device)
        optimizer.zero_grad()
        pred = model(batch)
        loss = criterion(pred, batch.y)
        loss.backward()
        optimizer.step()
        total_loss += loss.item() * batch.num_graphs

    if epoch % 10 == 0:
        print(f"Epoch {epoch:02d} | Train MSE Loss: {total_loss / len(train_loader.dataset):.4f}")

# 6. Evaluate Final Test Metrics
model.eval()
y_true, y_pred = [], []
with torch.no_grad():
    for batch in test_loader:
        batch = batch.to(device)
        preds = model(batch)
        y_true.extend(batch.y.cpu().numpy().flatten())
        y_pred.extend(preds.cpu().numpy().flatten())

gnn_mae = mean_absolute_error(y_true, y_pred)
gnn_r2 = r2_score(y_true, y_pred)

print("\n--- CGCNN Final Test Performance ---")
print(f"CGCNN Mean Absolute Error (MAE): {gnn_mae:.4f} mmol/g")
print(f"CGCNN Coefficient of Determination (R^2): {gnn_r2:.4f}")

